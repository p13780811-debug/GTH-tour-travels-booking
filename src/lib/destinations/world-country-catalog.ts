/** Exact stored labels and familiar display names both resolve to the same
 * authoritative ISO-2 identity. Never synthesize an unsupported country code.
 */
export function findDestinationCountry(input:unknown):WorldDestinationCountry|null{
 if(typeof input!=="string"||input.length>100||/[\u0000-\u001f\u007f<>]/u.test(input))return null;
 const text=input.normalize("NFKC").trim().toLocaleLowerCase("en");
 return WORLD_DESTINATION_COUNTRIES.find(item=>
  item.code.toLocaleLowerCase("en")===text||
  item.name.toLocaleLowerCase("en")===text||
  item.dbName.toLocaleLowerCase("en")===text)??null;
}
