import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");

test("blog catalog contains complete articles and no scaled autogenerated empty slugs", () => {
  const data = read("src/data/blogs.ts");
  assert.match(data, /how-to-compare-flight-fares/);
  assert.match(data, /hotel-booking-checklist/);
  assert.match(data, /secure-travel-bookings/);
  assert.doesNotMatch(data, /generateBlogs\(/);
  assert.doesNotMatch(data, /Math\.random/);
  assert.match(data, /content: `##/);
});

test("blog detail renders Markdown without HTML injection or fake fallback", () => {
  const detail = read("src/app/blog/[slug]/page.tsx");
  assert.match(detail, /ReactMarkdown/);
  assert.match(detail, /notFound\(\)/);
  assert.match(detail, /generateStaticParams/);
  assert.doesNotMatch(detail, /dangerouslySetInnerHTML|being curated by our AI engine/);
});

test("blog category links actually filter article list", () => {
  const page = read("src/app/blog/page.tsx");
  assert.match(page, /searchParams/);
  assert.match(page, /blogs\.filter/);
  assert.match(page, /new URLSearchParams\(\)/);
  assert.match(page, /params\.set\("category", category\)/);
  assert.match(page, /href="\/flights"/);
  assert.match(page, /href="\/hotels"/);
});

test("guides page contains articles rather than coming soon placeholder", () => {
  const page = read("src/app/guides/page.tsx");
  assert.match(page, /blogs\.map/);
  assert.match(page, /\/blog\/\$\{item\.slug\}/);
  assert.doesNotMatch(page, /coming soon|1% Education Fund/i);
});

test("destination articles and guide cards use actual editorial summaries", () => {
  const section = read("src/components/destination/BlogSection.tsx");
  const scroll = read("src/components/sections/GuidesScroll.tsx");
  assert.match(section, /blogs\[0\]\.description/);
  assert.match(scroll, /\/blog\/\$\{blog\.slug\}/);
});


test("editorial search and category filters link to complete real articles", () => {
  const listing = read("src/app/blog/page.tsx");
  const reader = read("src/app/blog/[slug]/page.tsx");
  const sitemap = read("src/app/sitemap.ts");
  assert.match(listing, /action="\/blog" method="get"/);
  assert.match(listing, /name="search"/);
  assert.match(listing, /articles = blogs\.filter/);
  assert.match(listing, /filterLink\(category, search\)/);
  assert.match(reader, /"\/blog\/" \+ item\.slug/);
  assert.match(reader, /ReactMarkdown/);
  assert.match(sitemap, /if \(!publicLaunch\) return \[\]/);
  assert.match(sitemap, /\.\.\.blogs\.map/);
});

test("global navigation keeps approved flagship isolated and links to Blog", () => {
  const nav = read("src/components/Navbar.tsx");
  assert.match(nav, /if \(pathname === "\/" \|\| pathname === "\/app"\) return null/);
  assert.match(nav, /name: "Blog", href: "\/blog"/);
  assert.match(nav, /name: "Destinations", href: "\/destinations"/);
});
