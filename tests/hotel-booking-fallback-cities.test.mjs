import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
function load(path,imports={}){
  const mod={exports:{}};
  vm.runInNewContext(ts.transpileModule(read(path),{
    compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}
  }).outputText,{
    module:mod,exports:mod.exports,URL,URLSearchParams,btoa,atob,
    require:name=>{if(name in imports)return imports[name];throw Error("Unexpected dependency "+name);}
  },{timeout:2000});
  return mod.exports;
}
const affiliate=load("src/lib/travel/partner-search.ts");
const hotelWhiteLabel=load("src/lib/travel/hotel-whitelabel.ts");
const routing=load("src/lib/travel/hotel-routing.ts",{"./hotel-whitelabel":hotelWhiteLabel});
const hotels=load("src/lib/travel/klook-hotel-search.ts",{"./partner-search":affiliate,"./hotel-routing":routing});

test("Goa and Dubai hotel handoffs target supplier HOTEL category with existing campaign",()=>{
  for(const [city,path] of [
    ["Goa","/destination/c178-goa/3-hotel/"],
    ["Dubai","/en-IN/destination/c78-dubai/3-hotel/"]
  ]){
    const link=hotels.trackedHotelCityHref(city);
    assert.ok(link);
    const affiliateUrl=new URL(link);
    assert.equal(affiliateUrl.origin,"https://tp.media");
    for(const [field,value] of Object.entries({campaign_id:"137",marker:"417668",p:"4110",trs:"504342",sub_id:"gth_hotels_"+city.toLowerCase()}))
      assert.equal(affiliateUrl.searchParams.get(field),value);
    const target=new URL(affiliateUrl.searchParams.get("u"));
    assert.equal(target.hostname,"www.klook.com");
    assert.equal(target.pathname,path);
    assert.equal(target.searchParams.size,0);
  }
});
test("Verified supplier hotel categories are generated by ONE worldwide resolver and tracked by the real affiliate marker",()=>{
 const cases={
   Goa:[178,"goa"],Dubai:[78,"dubai"],Singapore:[6,"singapore"],
   Tokyo:[28,"tokyo"],Bangkok:[4,"bangkok"],Bali:[8,"bali"],
   Paris:[107,"paris"],"New York":[93,"new-york"],
   Seoul:[13,"seoul"],"Kuala Lumpur":[49,"kuala-lumpur"],
   "Hong Kong":[2,"hong-kong"],Phuket:[7,"phuket"]
 };
 for(const [city,[id,slug]] of Object.entries(cases)){
   const referral=hotels.trackedHotelCityHref(city);
   assert.ok(referral,"Missing "+city);
   const url=new URL(referral);
   assert.equal(url.origin,"https://tp.media");
   assert.equal(url.searchParams.get("marker"),"417668");
   assert.equal(url.searchParams.get("campaign_id"),"137");
   assert.equal(url.searchParams.get("trs"),"504342");
   assert.equal(url.searchParams.get("p"),"4110");
   assert.equal(url.searchParams.get("sub_id"),"gth_hotels_"+city.toLowerCase().replace(/ /g,"_"));
   const supplier=new URL(url.searchParams.get("u"));
   assert.equal(supplier.hostname,"www.klook.com");
   assert.match(supplier.pathname,new RegExp("/destination/c"+id+"-"+slug+"/3-hotel/$"));
 }
 // Verified Nuitee Place IDs stay primary; no partner handoff regression.
 for(const city of ["Mumbai","London"]){
   assert.equal(hotels.trackedHotelCityHref(city),null,"Nuitee reviewed city must not be redirected to Klook");
   const direct=new URL(hotels.destinationHotelHref(city));
   assert.equal(direct.origin,"https://hotel.gthproglobal.com");
   assert.equal(direct.pathname,"/hotels");
   assert.ok(direct.searchParams.has("placeId"));
 }
 // Every verified alternative is a hotels listing, never a tours/search page.
 for(const city of ["Goa","Dubai","Tokyo","Singapore","Paris","New York","Bali","Bangkok","Seoul","Hong Kong","Phuket","Kuala Lumpur"]){
   assert.match(new URL(new URL(hotels.destinationHotelHref(city)).searchParams.get("u")).pathname,/\/3-hotel\/$/);
 }
 // Unknown destinations cannot select a fake hotel, city ID, or unrelated airport.
 for(const city of ["Kolkata","Abu Dhabi","Sydney","Tehran","Kathmandu"]){
   assert.equal(hotels.trackedHotelCityHref(city),null);
   const href=hotels.destinationHotelHref(city);
   assert.match(href,/^\/hotels\?view=booking&city=/);
   assert.equal(new URL(href,"https://gthproglobal.com").searchParams.get("city"),city);
 }
 assert.equal(new URL(new URL(hotels.trackedHotelCityHref("New York City")).searchParams.get("u")).pathname,
  "/en-US/destination/c93-new-york/3-hotel/");
});
