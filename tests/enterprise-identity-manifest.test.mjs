import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");

function buildGraph(){
  const source=read("src/components/seo/SiteIdentitySchema.tsx");
  const js=ts.transpileModule(source,{compilerOptions:{
    module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,
    jsx:ts.JsxEmit.ReactJSX,esModuleInterop:true,
  }}).outputText;
  const mod={exports:{}};
  const origin="https://www.gthproglobal.com/";
  const modules={
    "@/lib/site-config":{SITE_CONFIG:{contactEmail:"official@gthproglobal.com"}},
    "@/lib/seo/site":{
      siteUrl:p=>new URL(p,origin).toString(),
      safeStructuredData:obj=>JSON.stringify(obj).replace(/</g,"\\u003c"),
    },
    "react/jsx-runtime":{jsx:(tag,props)=>({tag,props}),jsxs:(tag,props)=>({tag,props})},
  };
  vm.runInNewContext(js,{
    module:mod,exports:mod.exports,
    require:key=>{
      assert.ok(Object.hasOwn(modules,key),"Unexpected schema dependency: "+key);
      return modules[key];
    },
  },{timeout:2500});
  const instance=mod.exports.default();
  assert.equal(instance.tag,"script");
  assert.equal(instance.props.type,"application/ld+json");
  return JSON.parse(instance.props.dangerouslySetInnerHTML.__html);
}

test("production root metadata is authoritative and old Next.js starter metadata is absent",()=>{
  const layout=read("src/app/layout.tsx");
  assert.match(layout,/GTH PRO Global \| Travel, Real Estate, Tenders & Worldwide Tickets/);
  assert.match(layout,/metadataBase: new URL\(siteOrigin\(\)\)/);
  assert.match(layout,/GTH_PUBLIC_LAUNCH_ENABLED/);
  assert.equal((layout.match(/<SiteIdentitySchema \/>/g)||[]).length,1);
  const head=layout.slice(layout.indexOf("<head>"),layout.indexOf("</head>"));
  assert.match(head,/<SiteIdentitySchema \/>/);
  assert.doesNotMatch(layout,/Generated by create next app|Welcome to Next\.js/i);
  assert.match(layout,/index: false, follow: false/);
  assert.doesNotMatch(layout,/<style>|service[_-]?role|SUPABASE_SERVICE_ROLE_KEY/);
});

test("one factual Organization and WebSite graph accurately describes four audited first-party routes",()=>{
  const data=buildGraph();
  assert.equal(data["@context"],"https://schema.org");
  assert.equal(data["@graph"].length,2);
  const org=data["@graph"].find(n=>n["@type"]==="Organization");
  const site=data["@graph"].find(n=>n["@type"]==="WebSite");
  assert.ok(org&&site);
  assert.equal(site.publisher["@id"],org["@id"]);
  assert.equal(org.email,"official@gthproglobal.com");
  assert.equal(org.hasOfferCatalog.itemListElement.length,4);
  const items=org.hasOfferCatalog.itemListElement;
  for(const route of ["/travel","/real-estate","/tender","/tickets"]){
    assert.ok(items.some(s=>s.url==="https://www.gthproglobal.com"+route),route);
  }
  assert.ok(site.hasPart.some(s=>s.url==="https://www.gthproglobal.com/gth-ecosystem-manifest"));
  assert.ok(org.subjectOf.some(s=>s.url==="https://www.gthproglobal.com/verification"));
  for(const item of site.hasPart){
    assert.ok(item.url.startsWith("https://www.gthproglobal.com/"),item.url);
    const path=new URL(item.url).pathname;
    assert.ok(existsSync(new URL("../src/app"+path+"/page.tsx",import.meta.url)),
      "Missing first-party public service route "+path);
  }
  const serialized=JSON.stringify(data);
  assert.doesNotMatch(serialized,/aggregateRating|reviewCount|governmentAgency|taxID|founder|security certified|100% verified|service.role|SUPABASE_SERVICE_ROLE_KEY/i);
  assert.match(org.description,/initiative of Etios Profession/);
  assert.match(org.description,/supplier-operated booking handoffs/);
});

test("manifest is a static source-grounded >500-word public document with official identity and release boundaries",()=>{
  const p=read("src/app/gth-ecosystem-manifest/page.tsx");
  const prose=p.replace(/<[^>]*>/g," ").replace(/\{[^{}]*\}/g," ").replace(/import[^\n]*\n/g," ");
  assert.ok(prose.trim().split(/\s+/).length>=500,"Manifest must contain at least 500 words");
  for(const term of ["Worldwide Travel","Global Real Estate","Public Tender Intelligence",
    "Worldwide Tickets and Venues","Etios Profession","Supabase","12,587","4,104","21,700","174,819"]){
    assert.ok(p.includes(term),"Manifest should describe audited evidence: "+term);
  }
  assert.match(p,/GTH_PUBLIC_LAUNCH_ENABLED|isPublicLaunch\(\)/);
  assert.match(p,/canonical: siteUrl\("\/gth-ecosystem-manifest"\)/);
  assert.match(p,/supplier|provider/i);
  assert.match(p,/not automatically accepted/i);
  assert.match(p,/until they are merged, successfully deployed and checked/i);
  assert.doesNotMatch(p,/"use client"|fetch\(|createClient\(|<style|style=\{|indexing is guaranteed|automatic certification/i);
  assert.match(p,/SITE_CONFIG\.contactEmail/);
});

